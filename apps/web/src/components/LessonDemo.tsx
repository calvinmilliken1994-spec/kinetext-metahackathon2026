import { useMemo, useState } from 'react';
import { collectLessonQuotes } from '../lib/lesson.ts';
import { demoLessons } from '../demo/lessonFixtures.ts';
import { LessonView } from './LessonView.tsx';
import type { CiteProps } from './Explanations.tsx';

const DEMO_DISCLOSURE = 'AI-written lesson text (demo fixture). Real lessons are written by Muse Spark 1.3 and checked against the page; this one is hand-written test data.';

function initialId(): string {
  const wanted = new URLSearchParams(window.location.search).get('lesson');
  return demoLessons.some((l) => l.id === wanted) ? (wanted as string) : (demoLessons[0]?.id ?? 'drag');
}

/**
 * Dev-only harness (?lesson-demo=1[&lesson=drag|gallery|partial|declined|premium]): renders the Stage 6 lesson views on
 * fixture data so they can be seen before the backend is wired. It is clearly marked as a demo and never calls a model or the API.
 */
export function LessonDemo() {
  const [id, setId] = useState<string>(initialId);
  const [toast, setToast] = useState('');
  const demo = demoLessons.find((l) => l.id === id) ?? demoLessons[0];
  const sourceId = demo?.sources[0]?.id ?? '';
  const located = useMemo(
    () => new Set((demo === undefined ? [] : collectLessonQuotes(sourceId, demo.lesson.overview, demo.specs)).map((q) => q.key)),
    [demo, sourceId],
  );
  if (demo === undefined) return null;
  const cite: CiteProps = {
    sourceId,
    located,
    onCite: (key) => setToast(`Demo: in the workspace this highlights the quote in the source panel (${key}).`),
  };
  const choose = (next: string): void => {
    setId(next);
    setToast('');
    const url = new URL(window.location.href);
    url.searchParams.set('lesson', next);
    window.history.replaceState(null, '', url);
  };

  return (
    <div className="demo-page">
      <h1 className="sr-only">Lesson views demo (fixture data)</h1>
      <div className="demo-banner" role="note" data-testid="demo-banner">
        <strong>DEMO — fixture data, not model output.</strong>{' '}
        These lessons are hand-written test fixtures (tests/fixtures/stage6) shown with the real lesson views. Nothing here was generated by a model or checked by a live run. This page exists only in development.
      </div>
      <nav className="demo-tabs" aria-label="Demo lessons">
        {demoLessons.map((l) => (
          <button key={l.id} type="button" className={`btn btn-small${l.id === id ? ' btn-primary' : ''}`} aria-current={l.id === id ? 'page' : undefined} onClick={() => choose(l.id)}>{l.tab}</button>
        ))}
      </nav>
      <p className="muted small demo-note">{demo.note}</p>
      <main className="activity-panel demo-main" aria-label="Interactive lesson">
        <LessonView
          key={demo.id}
          lesson={demo.lesson}
          specs={demo.specs}
          analysis={demo.analysis}
          sources={demo.sources}
          cite={cite}
          disclosure={DEMO_DISCLOSURE}
          premium={demo.premium}
        />
      </main>
      <p className="demo-toast small" role="status" aria-live="polite">{toast}</p>
    </div>
  );
}
